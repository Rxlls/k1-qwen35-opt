"""生成本项目的固定多轮测试集：12 段对话 × 3 轮，每段埋 2 个事实。

设计要点：
- 第 1 轮给材料 + 问事实 A；
- 第 2 轮追问事实 B（必须靠前文记忆）；
- 第 3 轮要求把 A、B 合起来算（跨轮综合）；
- 答案都是短值（数字/短语），可字符串匹配自动判分，不依赖裁判模型。
"""
import json

FILLER = (
    "本项目的推理服务部署在边缘设备上，需要在有限内存与算力下保持稳定。"
    "工程师先做了基线测量，再逐项替换变量，每次只改一个参数，以保证归因清楚。"
    "测量时统一关闭思考模式、温度设为 0，并按固定顺序执行，避免缓存干扰。"
)

# (对话 id, 主题, 事实A, 事实B, 综合题的期望结果)
CASES = [
    ("T01", "技术", ("可用内存", "4096 MiB"), ("线程数", "6"), ("可用内存÷线程数", "682")),
    ("T02", "技术", ("模型体积", "2.50 GiB"), ("峰值内存", "3.12 GiB"), ("两者相差多少 GiB（保留两位）", "0.62")),
    ("T03", "技术", ("首字延迟", "17.6 秒"), ("输入长度", "294 token"), ("输入翻倍到 588 token 时首字延迟约多少秒", "35")),
    ("T04", "生活", ("会议时间", "周三下午三点"), ("会议室", "B203"), ("会议在哪个会议室", "B203")),
    ("T05", "生活", ("航班号", "MU5137"), ("起飞时间", "08:40"), ("航班几点起飞", "08:40")),
    ("T06", "生活", ("预算", "1200 元"), ("人数", "8 人"), ("人均预算", "150")),
    ("T07", "数学", ("数列首项", "3"), ("公差", "5"), ("第 10 项", "48")),
    ("T08", "数学", ("长方形长", "12 厘米"), ("宽", "7 厘米"), ("面积", "84")),
    ("T09", "数学", ("折扣", "八折"), ("原价", "250 元"), ("折后价", "200")),
    ("T10", "代码", ("函数名", "load_model"), ("返回类型", "指针"), ("这个函数返回什么类型", "指针")),
    ("T11", "代码", ("日志级别", "WARN"), ("输出文件", "srv.log"), ("日志写到哪个文件", "srv.log")),
    ("T12", "代码", ("超时阈值", "30 秒"), ("重试次数", "3"), ("总等待上限", "90")),
]


def build():
    items = []
    for cid, topic, a, b, (q3_desc, expect3) in CASES:
        material = (
            FILLER
            + "补充记录：本段的%s是 %s。" % (a[0], a[1])
            + FILLER[:60]
            + "另一条记录：本段的%s是 %s。" % (b[0], b[1])
            + FILLER[:50]
        )
        items.append({
            "id": cid,
            "topic": topic,
            "turns": [
                {"user": material + "\n\n问题一：材料中记录的%s是多少？只回答数值或短语。" % a[0],
                 "expect": a[1].split()[0]},
                {"user": "问题二：那么材料中记录的%s是多少？只回答数值或短语。" % b[0],
                 "expect": b[1].split()[0]},
                {"user": "问题三：%s？只回答结果。" % q3_desc,
                 "expect": expect3},
            ],
        })
    return items


if __name__ == "__main__":
    data = build()
    with open("eval/multiturn_set.json", "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=1)
    print("生成 %d 段对话 × %d 轮 = %d 轮"
          % (len(data), len(data[0]["turns"]), sum(len(x["turns"]) for x in data)))
